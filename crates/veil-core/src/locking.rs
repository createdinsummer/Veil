//! 锁等待选项；数据库文件租约协议由 veil-service 实现。
//!
//! # 业务定位
//!
//! 本模块只定义"等锁"这一侧客户端需要的选项：最长等待多久、如何取消等待。
//! 真正的租约（某段时间内独占操作权的凭证）申请、续租、释放协议保存在容器库
//! `operation_locks` 表中，由 veil-service 集中定义（30 秒租约、5 秒续租、
//! 30 秒默认等待期限、20 毫秒等待退避），本模块不接触数据库。
//!
//! # 与并发语义的关系
//!
//! 同一范围允许多个共享读租约；共享写允许不保存租约的普通读取，排他写在
//! 申请时会阻止新的普通读取。普通读取不会阻止后续写入，因此不能保证读取
//! 期间内容稳定。等待期限使用单调计时，不受系统时间修改影响。
//!
//! 核心定义：LockMode 表达共享读、普通只读、共享写和排他写；as_str 提供兼容数据库的两档存储值；
//! LockOptions 保存超时与取消条件。依赖 Duration、Arc 和 AtomicBool，不创建后台线程或实际申请锁。
use std::{
    sync::{Arc, atomic::AtomicBool},
    time::Duration,
};

/// 文件或目录租约的访问模式。
///
/// 业务定位：描述申请方对目标资源想要的访问强度，决定能否与其他持锁者共存。
/// 持久化到容器库时只保留 `read` / `write` 两档（见 [`LockMode::as_str`]），
/// 与 `operation_locks.mode` 的取值兼容。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LockMode {
    /// SR：共享读锁。
    /// 业务含义：只读访问，同一文件的多个共享读锁可以并存，互不阻塞。
    Read,
    /// RO：不阻止写入，也不保存租约。
    /// 业务含义：不登记租约，因此不会阻止后续写入；申请时仍须等待重叠的排他写租约结束。
    /// 共享写租约不阻止这种读取，读取期间内容也不保证稳定。
    ReadOnly,
    /// SW：共享写锁，允许普通读取。
    /// 业务含义：写入时仍允许普通读取者通过；写入者之间仍互斥。
    SharedWrite,
    /// EW：排他写锁。
    /// 业务含义：排斥重叠范围内已登记的读写租约，并阻止后续普通读取申请；
    /// 已开始的普通读取没有登记租约，无法被这把锁追踪或阻止。
    Write,
}

impl LockMode {
    /// 与既有容器数据库兼容的存储值。
    ///
    /// 功能：把四种内存访问模式收敛为数据库 `operation_locks.mode` 字段的
    /// 两档取值，保证历史数据与新代码读写一致。
    ///
    /// 入参：`self` 为四种 `LockMode` 中的一种。
    /// 返回值：`"read"` 对应共享读与只读模式，`"write"` 对应共享写与排他写模式。
    /// 异常：不会返回错误或主动触发 panic。
    /// 注意：普通只读不插入租约行；共享写还需结合资源前缀区分，不能仅凭此值判断兼容性。
    pub fn as_str(self) -> &'static str {
        match self {
            // 两种读取映射到相同的数据库模式值；普通只读本身并不创建租约行。
            Self::Read | Self::ReadOnly => "read",
            // 两种写入均映射为 "write"；共享写通过资源前缀保留额外语义。
            Self::SharedWrite | Self::Write => "write",
        }
    }
}
/// 申请或等待租约时的客户端选项集合。
///
/// 业务定位：把"等多久、能不能中途取消"这类等待策略从各调用点收拢到一处，
/// service 的 default_options 使用 30 秒等待期限；直接使用本类型派生的 Default 则为 timeout=None，允许无限等待。
#[derive(Clone, Default)]
pub struct LockOptions {
    /// 单调计时的最长等待时间；None 允许一直等待。
    /// 业务含义：申请锁失败后愿意等待多久；用单调时钟计时，不受系统时间回拨影响。
    pub timeout: Option<Duration>,
    /// 仅取消等待，不能提前结束仍在运行的阻塞工作。
    /// 业务含义：共享的取消开关；置位后放弃等待，但已拿到的租约和进行中的
    /// 流式加密/解密不会被误释放——取消等待≠取消正在执行的工作。
    pub cancellation: Option<Arc<AtomicBool>>,
}
