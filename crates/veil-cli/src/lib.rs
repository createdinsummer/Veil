//! Veil CLI 的可复用库入口。
//!
//! 本库暴露命令实现、国际化、提示渲染和终端输出编码，供二进制入口及集成测试复用。
//! 终端参数解析和进程退出仍由 `main.rs` 负责；可失败业务接口通常返回 Result，
//! 部分显示/配置辅助函数使用普通返回值、忽略底层结果或可能 panic，不能理解为所有错误都统一转换。
//!
//! 核心清单：`commands` 各子命令与密码输入辅助、`error` 稳定错误码与退出码、
//! `hints` 一次性操作提示、`i18n` 中英文消息表、`output_encoding` 终端编码适配。

/// 各子命令实现及命令层公共辅助函数（容器解析、密码输入、服务请求转发）。
pub mod commands;
/// 稳定错误码、模板参数、退出码及 `cli_error!`/`cli_bail!` 构造宏。
pub mod error;
/// 一次性操作提示（首次创建/打包/解包、链接恢复）的判定与渲染。
pub mod hints;
/// 编译期内嵌的中英文消息表与占位符替换。
pub mod i18n;
/// 终端显示编码适配与可失败的 `outln!`/`out!` 输出宏。
pub mod output_encoding;
